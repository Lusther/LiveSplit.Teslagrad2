using System.Linq;

namespace LiveSplit.Teslagrad2
{
    public class GameBuild
    {
        // Steam depot build id
        public int BuildId { get; }
        // Steam branch the build was published on
        public string Branch { get; }
        // TimeDateStamp from the GameAssembly.dll PE header, unique per compilation
        public uint Timestamp { get; }
        public int ModuleSize { get; }

        // RVAs of the Game, PlayerSceneHandler, SaveDataFile and Player TypeInfo globals in GameAssembly.dll
        public int BaseSaveDataSlot { get; }
        public int BaseSceneHandler { get; }
        public int BaseSaveDataFile { get; }
        public int BasePlayer { get; }

        public GameBuild(int buildId, string branch, uint timestamp, int moduleSize,
            int saveDataSlot, int sceneHandler, int saveDataFile, int player)
        {
            BuildId = buildId;
            Branch = branch;
            Timestamp = timestamp;
            ModuleSize = moduleSize;
            BaseSaveDataSlot = saveDataSlot;
            BaseSceneHandler = sceneHandler;
            BaseSaveDataFile = saveDataFile;
            BasePlayer = player;
        }

        public override string ToString() => $"build {BuildId} ({Branch})";
    }

    public static class Teslagrad2Constants
    {
        // Generated by tools/Update-Offsets.ps1, newest first. Columns:
        // build id, branch, GameAssembly.dll timestamp, module size, Game, PlayerSceneHandler, SaveDataFile, Player
        public static readonly GameBuild[] Builds =
        {
            new GameBuild(23225880, "public", 0x6A0376AF, 48156672, 0x2775B40, 0x273C238, 0x274A470, 0x273B718),
            new GameBuild(20406723, "public", 0x68E67AE2, 48156672, 0x2775B38, 0x273C230, 0x274A468, 0x273B710),
            new GameBuild(17572578, "old_version_for_speedrunning", 0x67C0D98B, 47239168, 0x2667C18, 0x269B9F8, 0x263BE40, 0x269AED0),
        };

        // Module size alone is not enough: a recompile can keep the same size while moving every offset
        public static GameBuild DetectBuild(uint timestamp)
        {
            return Builds.FirstOrDefault(b => b.Timestamp == timestamp);
        }
    }

