    public class GameBuild
    {
        // Steam depot build id
        public int BuildId { get; }
        // Steam branch the build was published on
        public string Branch { get; }
        // TimeDateStamp from the GameAssembly.dll PE header, unique per compilation
        public uint Timestamp { get; }
        public int ModuleSize { get; }

        // RVAs of the Game, PlayerSceneHandler and SaveDataFile TypeInfo globals in GameAssembly.dll
        public int BaseSaveDataSlot { get; }
        public int BaseSceneHandler { get; }
        public int BaseSaveDataFile { get; }

        public GameBuild(int buildId, string branch, uint timestamp, int moduleSize,
            int saveDataSlot, int sceneHandler, int saveDataFile)
        {
            BuildId = buildId;
            Branch = branch;
            Timestamp = timestamp;
            ModuleSize = moduleSize;
            BaseSaveDataSlot = saveDataSlot;
            BaseSceneHandler = sceneHandler;
            BaseSaveDataFile = saveDataFile;
        }

        public override string ToString() => $"build {BuildId} ({Branch})";
    }

